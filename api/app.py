def _texto(el, xpath, ns=NS):

    nodo = el.find(xpath, ns)

    return nodo.text.strip() if nodo is not None and nodo.text else ""



"""Se le pasa una licitación, y se le da formato a los campos buscados (diccionario)



Devuelve texto_evaluacion, string que se le pasa al LLM

"""



def parsear_entrada_xml(entry):

    titulo = _texto(entry, "atom:title")

    enlace_el = entry.find("atom:link", NS)

    enlace = enlace_el.get("href") if enlace_el is not None else ""



    txt_fecha = _texto(entry, "atom:updated") or _texto(entry, "atom:published")

    fecha_str = txt_fecha.split("T")[0] if txt_fecha else ""



    # Importe

    importe = 0.0

    try:

        presupuesto_el = entry.find(".//cbc-place-ext:EstimatedOverallContractAmount", NS)

        if presupuesto_el is None:

            presupuesto_el = entry.find(".//cbc:PayableAmount", NS)

        if presupuesto_el is not None and presupuesto_el.text:

            importe = float(presupuesto_el.text.replace(",", "."))

    except Exception:

        pass



    # Órgano Contratante

    organo = ""

    try:

        organo_el = entry.find(".//cac-place-ext:ContractingParty//cbc-place-ext:PartyName//cbc-place-ext:Name", NS)

        if organo_el is None:

            organo_el = entry.find(".//cac:ContractingParty//cbc:Name", NS)

        organo = organo_el.text.strip() if organo_el is not None and organo_el.text else ""

    except Exception:

        pass



    # Descripción del Objeto

    descripcion = _texto(entry, ".//cac-place-ext:ContractFolderStatus/cac:ProcurementProject/cbc:Name", NS)

    if not descripcion:

        descripcion = _texto(entry, ".//cac:ProcurementProject/cbc:Description", NS)



    #  Lugar de Ejecución (NUTS, Ciudad / Dirección) ---

    lugar_ejecucion = ""

    try:

        realized_loc = entry.find(".//cac-place-ext:ContractFolderStatus/cac:ProcurementProject/cac:RealizedLocation", NS)

        if realized_loc is not None:

            nuts = _texto(realized_loc, ".//cbc:CountrySubentityCode", NS)

            ciudad = _texto(realized_loc, ".//cbc:CityName", NS)

            pais = _texto(realized_loc, ".//cac:Country/cbc:IdentificationCode", NS)



            partes_lugar = [p for p in [ciudad, nuts, pais] if p]

            lugar_ejecucion = " - ".join(partes_lugar) if partes_lugar else ""

    except Exception:

        pass



    # Fecha y Hora Límite de Ofertas ---

    plazo_ofertas = ""

    try:

        deadline_el = entry.find(".//cac-place-ext:ContractFolderStatus/cac:TenderingProcess/cac:TenderSubmissionDeadlinePeriod", NS)

        if deadline_el is not None:

            f_fin = _texto(deadline_el, "cbc:EndDate", NS)

            h_fin = _texto(deadline_el, "cbc:EndTime", NS)

            desc_plazo = _texto(deadline_el, "cbc:Description", NS)



            if f_fin:

                plazo_ofertas = f"{f_fin} {h_fin}".strip()

            elif desc_plazo:

                plazo_ofertas = desc_plazo

    except Exception:

        pass



    texto_evaluacion = f"passage: Título: {titulo}. Objeto del contrato: {descripcion}. Órgano: {organo}. Lugar: {lugar_ejecucion}. Plazo presentación: {plazo_ofertas}"



    return {

        "titulo": titulo,

        "organo": organo,

        "fecha": fecha_str,

        "importe": importe,

        "enlace": enlace,

        "lugar": lugar_ejecucion,

        "plazo_ofertas": plazo_ofertas,

        "texto_completo": texto_evaluacion

    }



"""Por cada zip, entra y lee todos los ficheros .atom o .xml y los transforma para devolver una lista con las licitaciones estructuradas para poder trabajar con ellas"""



def procesar_zip_local(ruta_zip):

    licitaciones = []

    try:

        with zipfile.ZipFile(ruta_zip, 'r') as z:

            for nombre_archivo in z.namelist():

                if nombre_archivo.endswith('.atom') or nombre_archivo.endswith('.xml'):

                    with z.open(nombre_archivo) as f:

                        contenido = f.read()

                        try:

                            root = ET.fromstring(contenido)

                            entradas = root.findall("atom:entry", NS)

                            for entry in entradas:

                                licitaciones.append(parsear_entrada_xml(entry))

                        except ET.ParseError:

                            continue

    except Exception as e:

        print(f"  ❌ Error procesando el archivo {ruta_zip}: {e}")

    return licitaciones



