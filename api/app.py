@app.post("/api/buscar")
def api_buscar(payload: dict):
    global GLOBAL_DF, GLOBAL_EMBEDDINGS
    if GLOBAL_DF.empty:
        return {"resultados": [], "mensaje": "La base de datos está vacía. Sincroniza novedades."}

    df = GLOBAL_DF.copy()
    total_leidas = len(df)

    consulta = payload.get("consulta", "")
    organo_filtro = payload.get("organo", "").lower()
    f_desde = payload.get("fecha_desde", "")
    f_hasta = payload.get("fecha_hasta", "")
    i_min = payload.get("importe_min", 0)
    i_max = payload.get("importe_max", 0)
    umbral = payload.get("umbral", 0.7)

    if f_desde:
        df = df[df["fecha"] >= f_desde]
    if f_hasta:
        df = df[df["fecha"] <= f_hasta]
    if i_min and i_min > 0:
        df = df[df["importe"] >= i_min]
    if i_max and i_max > 0:
        df = df[df["importe"] <= i_max]
    if organo_filtro:
        df = df[df["organo"].str.lower().str.contains(organo_filtro, na=False)]

    if df.empty:
        return {"resultados": [], "mensaje": f"No hay resultados con esos filtros sobre {total_leidas} licitaciones."}

    if consulta and consulta.strip():
        model = get_encoder()
        indices = df.index.tolist()
        embeddings_filtrados = GLOBAL_EMBEDDINGS[indices] if GLOBAL_EMBEDDINGS is not None and len(GLOBAL_EMBEDDINGS) == len(GLOBAL_DF) else model.encode(df["texto_completo"].tolist())

        query_con_prefijo = f"query: {consulta.strip()}"
        embedding_query = model.encode([query_con_prefijo])
        similitudes = cosine_similarity(embedding_query, embeddings_filtrados)[0]

        df["Relevancia"] = np.round(similitudes * 100, 2)
        df = df[df["Relevancia"] >= (umbral * 100)]
        df = df.sort_values("Relevancia", ascending=False)
    else:
        df["Relevancia"] = 100.0
        df = df.sort_values("fecha", ascending=False)

    resultados = []
    for _, row in df.head(100).iterrows():
        resultados.append({
            "titulo": row.get("titulo", ""),
            "organo": row.get("organo", ""),
            "fecha": row.get("fecha", ""),
            "importe": row.get("importe", 0.0),
            "enlace": row.get("enlace", ""),
            "relevancia": row.get("Relevancia", 100.0)
        })

    return {
        "resultados": resultados,
        "mensaje": f"Se encontraron {len(resultados)} licitaciones (analizadas {total_leidas})."
    }

@app.post("/api/actualizar")
def api_actualizar():
    global GLOBAL_DF, GLOBAL_EMBEDDINGS
    model = get_encoder()
    enlaces_conocidos = set(GLOBAL_DF["enlace"]) if not GLOBAL_DF.empty else set()
    nuevas_totales = []

    headers = {'User-Agent': 'Mozilla/5.0'}
    for fuente in FUENTES:
        try:
            url = fuente["url"]
            resp = requests.get(url, headers=headers, timeout=30)
            if resp.status_code == 200:
                root = ET.fromstring(resp.content)
                for entry in root.findall("atom:entry", NS):
                    datos = parsear_entrada_xml(entry)
                    if datos["enlace"] not in enlaces_conocidos:
                        nuevas_totales.append(datos)
                        enlaces_conocidos.add(datos["enlace"])
        except Exception as e:
            print(f"Error en fuente: {e}")

    if not nuevas_totales:
        return {"mensaje": "La base de datos ya está al día. No hay novedades."}

    df_nuevas = pd.DataFrame(nuevas_totales)
    nuevos_embeddings = model.encode(df_nuevas["texto_completo"].tolist(), show_progress_bar=False)

    if GLOBAL_DF.empty:
        GLOBAL_DF = df_nuevas
        GLOBAL_EMBEDDINGS = nuevos_embeddings
    else:
        GLOBAL_DF = pd.concat([df_nuevas, GLOBAL_DF], ignore_index=True)
        GLOBAL_EMBEDDINGS = np.vstack([nuevos_embeddings, GLOBAL_EMBEDDINGS])

    try:
        GLOBAL_DF.to_pickle(CACHE_DB)
        np.save(CACHE_EMB, GLOBAL_EMBEDDINGS)
    except Exception:
        pass

