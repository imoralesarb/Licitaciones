def obtener_novedades_fuente(url_fuente, enlaces_conocidos):

    """

    Recorre TODAS las páginas disponibles en el feed de internet de la PLACSP,

    ignora los enlaces que ya existan en Drive y acumula todo lo nuevo/faltante,

    sin importar si hay fechas salteadas o huecos en el histórico.

    """

    licitaciones_nuevas = []

    url_actual = url_fuente

    paginas_leidas = 0



    headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}



    print(f"🌐 Iniciando barrido completo del feed de internet...")



    while url_actual:

        try:

            resp = requests.get(url_actual, headers=headers, timeout=30)

            if resp.status_code != 200:

                print(f"⚠️ Error HTTP {resp.status_code} al acceder al feed.")

                break



            root = ET.fromstring(resp.content)

            entradas = root.findall("atom:entry", NS)



            if not entradas:

                break



            paginas_leidas += 1

            nuevas_en_esta_pagina = 0



            for entry in entradas:

                datos = parsear_entrada_xml(entry)



                # Si ya lo tenemos en Drive, lo saltamos pero SEGUIMOS buscando

                if datos["enlace"] in enlaces_conocidos:

                    continue



                # Si no lo teníamos, lo añadimos a la lista de novedades

                licitaciones_nuevas.append(datos)

                enlaces_conocidos.add(datos["enlace"]) # Evita duplicados dentro del mismo proceso

                nuevas_en_esta_pagina += 1



            # Buscar la siguiente página del feed ATOM

            next_link = root.find("atom:link[@rel='next']", NS)

            if next_link is not None:

                url_actual = next_link.get("href")

            else:

                break # Se acabaron las páginas en internet



        except Exception as e:

            print(f"❌ Error procesando el feed {url_actual}: {e}")

            break



    print(f"✨ Barrido finalizado. Páginas leídas: {paginas_leidas}. Licitaciones nuevas/faltantes encontradas: {len(licitaciones_nuevas)}")

    return licitaciones_nuevas



