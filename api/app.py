def busqueda_hibrida(consulta_texto, fecha_desde, fecha_hasta, importe_min, importe_max, Umbral_Similitud=0.80):

    global GLOBAL_DF, GLOBAL_EMBEDDINGS, ULTIMOS_RESULTADOS



    inicio_tiempo = time.time()



    if GLOBAL_DF.empty:

        ULTIMOS_RESULTADOS = pd.DataFrame()

        return pd.DataFrame(), "La base de datos está vacía. Haz clic en 'Buscar Novedades en Internet' para descargar datos."



    df = GLOBAL_DF.copy()

    total_leidas = len(df)



    # Filtros de Fecha e Importe

    if fecha_desde and fecha_desde.strip():

        df = df[df["fecha"] >= fecha_desde.strip()]

    if fecha_hasta and fecha_hasta.strip():

        df = df[df["fecha"] <= fecha_hasta.strip()]

    if importe_min and importe_min > 0:

        df = df[df["importe"] >= importe_min]

    if importe_max and importe_max > 0:

        df = df[df["importe"] <= importe_max]



    if df.empty:

        t_transcurrido = round(time.time() - inicio_tiempo, 3)

        ULTIMOS_RESULTADOS = pd.DataFrame()

        return pd.DataFrame(), f"No hay resultados con esos filtros sobre las {total_leidas} licitaciones ({t_transcurrido}s)."



    # Búsqueda Vectorial por Similitud

    if consulta_texto and consulta_texto.strip():

        indices = df.index.tolist()

        embeddings_filtrados = GLOBAL_EMBEDDINGS[indices]



        query_con_prefijo = f"query: {consulta_texto.strip()}"

        embedding_query = encoder.encode([query_con_prefijo])



        similitudes = cosine_similarity(embedding_query, embeddings_filtrados)[0]



        df["Relevancia (%)"] = np.round(similitudes * 100, 2)

        df = df[df["Relevancia (%)"] >= (Umbral_Similitud * 100)]

        df = df.sort_values("Relevancia (%)", ascending=False)

    else:

        df["Relevancia (%)"] = 100.0

        df = df.sort_values("fecha", ascending=False)



    df_export = df.copy()



    # Formato enlace web

    estilo_link = "color: #2563eb; font-weight: bold; text-decoration: underline;"

    df["Enlace"] = df["enlace"].apply(

        lambda x: f'<a href="{x}" target="_blank" style="{estilo_link}">Ver licitación 🔗</a>' if x else ""

    )



    df = df.reset_index(drop=True)

    df["#"] = df.index + 1



    df_export = df_export.reset_index(drop=True)

    df_export["#"] = df_export.index + 1



    df = df.rename(columns={"titulo": "Título", "fecha": "Fecha", "importe": "Importe"})

    res_df = df[["#", "Relevancia (%)", "Título", "Fecha", "Importe", "Enlace"]]



    df_export = df_export.rename(columns={"titulo": "Título", "fecha": "Fecha", "importe": "Importe", "enlace": "Enlace", "organo": "Órgano Contratante"})

    ULTIMOS_RESULTADOS = df_export[["#", "Relevancia (%)", "Título", "Órgano Contratante", "Fecha", "Importe", "Enlace"]]



    t_transcurrido = round(time.time() - inicio_tiempo, 3)

    msg = f"Búsqueda completada en **{t_transcurrido}s**: **{len(res_df)}** licitaciones encontradas de **{total_leidas}** analizadas."



